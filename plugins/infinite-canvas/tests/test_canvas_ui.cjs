const fs = require('fs');
const path = require('path');
const assert = require('assert');

const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'ui', 'CanvasApplication.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'ui', 'CanvasApplication.css'), 'utf8');
const bundle = fs.readFileSync(path.join(root, 'ui', 'dist', 'index.js'), 'utf8');
const examplesDir = path.join(root, 'work', 'examples');
const examples = fs.readdirSync(examplesDir).filter(name => name.endsWith('.json'));
assert.ok(examples.length >= 3, 'the plugin must ship shareable workflow examples');
for (const name of examples) {
  const workflow = JSON.parse(fs.readFileSync(path.join(examplesDir, name), 'utf8'));
  assert.equal(workflow.schema_version, 1, `${name} must use schema version 1`);
  assert.equal(workflow.kind, 'videofree.infinite-canvas', `${name} must use the canvas workflow kind`);
  const nodeIds = new Set(workflow.nodes.map(node => node.id));
  assert.ok(workflow.nodes.length > 0, `${name} must contain nodes`);
  for (const edge of workflow.edges) {
    assert.ok(nodeIds.has(edge.from.node) && nodeIds.has(edge.to.node), `${name} must reference existing nodes`);
  }
}

